// ─── Loading Screen ─────────────────────────────────────────────────────────
function initLoadingScreen() {
  const screen = document.getElementById('loading-screen');
  const fill   = document.getElementById('load-bar-fill');
  const wrapper = document.getElementById('main-wrapper');

  let progress = 0;
  const interval = setInterval(() => {
    progress = Math.min(progress + Math.random() * 15 + 5, 100);
    if (fill) fill.style.width = progress + '%';
    if (progress >= 100) {
      clearInterval(interval);
      setTimeout(() => {
        if (screen) { screen.style.opacity = '0'; screen.style.transition = 'opacity 0.4s'; setTimeout(() => { screen.style.display = 'none'; }, 400); }
        if (wrapper) wrapper.classList.add('loaded');
      }, 300);
    }
  }, 120);
}

// ─── Reading Progress ────────────────────────────────────────────────────────
function initReadingProgress() {
  const bar = document.getElementById('reading-progress');
  window.addEventListener('scroll', () => {
    const total = document.documentElement.scrollHeight - window.innerHeight;
    if (bar) bar.style.width = ((window.scrollY / total) * 100) + '%';
  }, { passive: true });
}

// ─── Navbar ──────────────────────────────────────────────────────────────────
function initNavbar() {
  const navbar = document.getElementById('navbar');
  const hamburger = document.getElementById('hamburger');
  const mobileMenu = document.getElementById('mobile-menu');
  const hamburgerIcon = document.getElementById('hamburger-icon');

  // Scroll behavior
  window.addEventListener('scroll', () => {
    if (!navbar) return;
    if (window.scrollY > 60) navbar.classList.add('scrolled');
    else navbar.classList.remove('scrolled');
  }, { passive: true });

  // Hamburger toggle
  if (hamburger && mobileMenu) {
    hamburger.addEventListener('click', () => {
      const isOpen = mobileMenu.classList.toggle('open');
      if (hamburgerIcon) hamburgerIcon.innerHTML = isOpen ? icons.x : icons.menu;
    });
  }

  // Nav link clicks
  document.querySelectorAll('[data-nav]').forEach(btn => {
    btn.addEventListener('click', () => {
      const href = btn.getAttribute('data-nav');
      scrollToSection(href);
      setActiveNav(href);
      if (mobileMenu) mobileMenu.classList.remove('open');
      if (hamburgerIcon) hamburgerIcon.innerHTML = icons.menu;
    });
  });

  // Active nav on scroll
  const sections = NAV_ITEMS.map(n => document.querySelector(n.href)).filter(Boolean);
  window.addEventListener('scroll', () => {
    let current = NAV_ITEMS[0].href;
    sections.forEach(sec => {
      if (window.scrollY >= sec.offsetTop - 100) current = '#' + sec.id;
    });
    setActiveNav(current);
  }, { passive: true });
}

function setActiveNav(href) {
  document.querySelectorAll('[data-nav]').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-nav') === href);
  });
}

function scrollToSection(href) {
  const el = document.querySelector(href);
  if (el) el.scrollIntoView({ behavior: 'smooth' });
}

// ─── Intersection Observer Reveals ──────────────────────────────────────────
function initReveal() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });

  document.querySelectorAll('.reveal, .reveal-left, .reveal-right').forEach(el => observer.observe(el));
}

// ─── Back to Top ─────────────────────────────────────────────────────────────
function initBackToTop() {
  const btn = document.getElementById('back-to-top');
  if (!btn) return;
  window.addEventListener('scroll', () => {
    btn.classList.toggle('visible', window.scrollY > 400);
  }, { passive: true });
  btn.addEventListener('click', () => window.scrollTo({ top: 0, behavior: 'smooth' }));
}

